"""
annotate.py -- Collect human ratings, and measure the reward against them.

    python benchmark/annotate.py --build --from benchmark/results/run_<ts>_reward.json
    python benchmark/annotate.py --annotate --annotator alice
    python benchmark/annotate.py --annotate --annotator bob --overlap-only
    python benchmark/annotate.py --report

The reward in `src/reward/` is verifiable: recomputing it gives the same number.
That is not the same as valid, which would mean it tracks what a person would
choose. This collects the evidence for the second claim WITHOUT touching the
first -- nothing here writes a reward, and `score_rewards.py --verify` keeps
passing throughout.

Three files, under `feedback/`:

    instrument_<ts>.json   what the annotator sees. Hand this over.
    keymap_<ts>.json       which arm each item came from. Do NOT hand this over.
    responses_<name>.json  one per annotator, written after every answer.

The split is the blinding. An annotator with a text editor can read an arm name
out of a single combined file, and on a study this small one peek contaminates
the result.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "benchmark"))

from console import enable_utf8_stdout  # noqa: E402
from evaluator import _RUBRIC  # noqa: E402
from reward.agreement import (judge_vs_human, pairwise_accuracy,  # noqa: E402
                              rater_reliability, reward_vs_human)
from reward.annotation import build_instrument  # noqa: E402

enable_utf8_stdout()

FEEDBACK_DIR = ROOT / "feedback"
RULE = "-" * 78


# ── storage ──────────────────────────────────────────────────────────────────

def _load(p: Path) -> Dict[str, Any]:
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def _save(p: Path, payload: Dict[str, Any]) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    with open(p, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2, ensure_ascii=False)


def _newest(pattern: str) -> Optional[Path]:
    found = sorted(FEEDBACK_DIR.glob(pattern))
    return found[-1] if found else None


def _resolve_instrument(explicit: Optional[str]) -> Optional[Path]:
    """
    The instrument to work against, or None with the reason already printed.

    Checks existence here rather than letting `_load` raise. A missing path used
    to surface as a bare FileNotFoundError traceback from `--annotate`, and as a
    message about a missing *keymap* from `--report` -- which named the wrong
    file and sent the reader looking for the wrong thing.
    """
    if explicit:
        p = Path(explicit)
        if not p.exists():
            print(f"No such instrument: {p}")
            available = sorted(FEEDBACK_DIR.glob("instrument_*.json"))
            if available:
                print("Available:")
                for a in available:
                    print(f"  {a}")
            else:
                print("Build one with:  python benchmark/annotate.py --build "
                      "--from benchmark/results/<run>_reward.json")
            return None
        return p

    p = _newest("instrument_*.json")
    if p is None:
        print("No instrument found in feedback/. Build one with:")
        print("  python benchmark/annotate.py --build "
              "--from benchmark/results/<run>_reward.json")
    return p


def _responses_path(annotator: str) -> Path:
    safe = "".join(c for c in annotator.lower() if c.isalnum() or c in "-_") or "anon"
    return FEEDBACK_DIR / f"responses_{safe}.json"


# ── prompting ────────────────────────────────────────────────────────────────

class Quit(Exception):
    """The annotator asked to stop. Everything answered so far is already saved."""


def _ask(prompt: str, lo: float, hi: float, integer: bool) -> Optional[float]:
    """
    One bounded numeric answer, or a control command.

    Re-asks on anything unparseable rather than recording a guess: a mistyped
    rating is worse than a slower session, and this is data that cannot be
    regenerated by re-running something.
    """
    while True:
        raw = input(prompt).strip().lower()
        if raw in ("q", "quit"):
            raise Quit
        if raw in ("r", "rubric"):
            print("\n" + _RUBRIC + "\n")
            continue
        if raw in ("s", "skip", ""):
            return None
        try:
            value = float(raw)
        except ValueError:
            print("  Enter a number between %g and %g, or r / s / q." % (lo, hi))
            continue
        if not lo <= value <= hi:
            print("  Out of range: expected %g to %g." % (lo, hi))
            continue
        return int(round(value)) if integer else value


def _screen(header: str, blocks: List[tuple]) -> None:
    print("\n" + RULE)
    print(header)
    print(RULE)
    for label, body in blocks:
        first, *rest = str(body).splitlines() or [""]
        print("%-9s %s" % (label, first))
        for line in rest:
            print("%-9s %s" % ("", line))
        print()
    print(RULE)


# ── commands ─────────────────────────────────────────────────────────────────

def cmd_build(args: argparse.Namespace) -> int:
    reward_path = Path(args.source)
    if not reward_path.exists():
        print(f"No such reward file: {reward_path}")
        results = ROOT / "benchmark" / "results"
        found = sorted(results.glob("*_reward.json"))
        if found:
            print("Available:")
            for f in found:
                print(f"  {f.relative_to(ROOT)}")
        else:
            print("None exist yet. Produce one with:")
            print("  python benchmark/score_rewards.py "
                  "benchmark/results/<run>.json --verify --sensitivity")
        return 1
    run_path = reward_path.with_name(reward_path.name.replace("_reward.json", ".json"))
    eval_path = reward_path.with_name(reward_path.name.replace("_reward.json", "_eval.json"))
    if not run_path.exists():
        print(f"Cannot find the results file beside {reward_path.name}: {run_path}")
        return 1

    reward = _load(reward_path)
    if (reward.get("metadata") or {}).get("synthetic"):
        print("!" * 70)
        print("SYNTHETIC RUN. Rating mock output measures the mock, not the system.")
        print("!" * 70)

    instrument, keymap = build_instrument(
        _load(run_path), reward,
        _load(eval_path) if eval_path.exists() else None,
        n_items=args.n_items, n_pairs=args.n_pairs,
        repeat_fraction=args.repeat_fraction, overlap_items=args.overlap,
        seed=args.seed)

    ts = instrument["metadata"]["created"]
    ip, kp = FEEDBACK_DIR / f"instrument_{ts}.json", FEEDBACK_DIR / f"keymap_{ts}.json"
    _save(ip, instrument)
    _save(kp, keymap)

    m = instrument["metadata"]
    print(f"\nBuilt from {reward_path.name}")
    print(f"  {m['n_unique_items']} distinct menus, {m['n_items']} rating screens "
          f"({m['n_items'] - m['n_unique_items']} repeats for intra-rater agreement)")
    print(f"  {m['n_pairs']} preference pairs")
    # Counted from the keymap: the stratum is not in the instrument, because
    # "safety_contrast" would tell the annotator one of the pair is unsafe.
    from collections import Counter
    for stratum, n in sorted(Counter(v["stratum"] for v in keymap["pairs"].values()).items()):
        print(f"      {stratum:<18} {n}")
    print(f"  first {m['overlap_items']} items are the second-annotator overlap")
    print(f"\n  hand over : {ip}")
    print(f"  keep back : {kp}")
    print(f"\nThen: python benchmark/annotate.py --annotate --annotator <name>")
    return 0


def cmd_annotate(args: argparse.Namespace) -> int:
    ip = _resolve_instrument(args.instrument)
    if ip is None:
        return 1
    instrument = _load(ip)

    rp = _responses_path(args.annotator)
    responses = _load(rp) if rp.exists() else {
        "metadata": {"annotator": args.annotator, "instrument": ip.name,
                     "instrument_version": instrument["metadata"]["instrument_version"],
                     "reward_version": instrument["metadata"].get("reward_version"),
                     "judge_rubric_version": instrument["metadata"].get("judge_rubric_version"),
                     "started": time.strftime("%Y%m%d_%H%M%S")},
        "ratings": [], "preferences": [],
    }
    if responses["metadata"].get("instrument") != ip.name:
        print(f"{rp.name} was recorded against {responses['metadata'].get('instrument')}, "
              f"not {ip.name}. Ratings of different menus must not be pooled.")
        return 1

    items = {i["item_id"]: i for i in instrument["items"]}
    order = instrument["item_order"]
    if args.overlap_only:
        order = order[:instrument["metadata"]["overlap_items"]]
    done_items = {r["item_id"] for r in responses["ratings"]}
    done_pairs = {p["pair_id"] for p in responses["preferences"]}

    todo = [i for i in order if i not in done_items]
    pairs = [] if args.overlap_only else [p for p in instrument["pairs"]
                                          if p["pair_id"] not in done_pairs]

    print(f"\nAnnotator: {args.annotator}   Instrument: {ip.name}")
    print(f"{len(todo)} ratings and {len(pairs)} pairs remaining.")
    print("At any prompt:  r = show the rubric   s = skip   q = save and quit")
    print("Everything is saved after each answer, so stopping loses nothing.")

    try:
        for n, item_id in enumerate(todo, 1):
            item = items[item_id]
            _screen(f"Rating {n} of {len(todo)}",
                    [("PROFILE", item["profile_text"]),
                     ("SOURCE", item["source_text"]),
                     ("MENU", item["menu_text"])])
            rating = {"item_id": item_id, "annotator": args.annotator,
                      "relevance": _ask("Relevance    1-5 > ", 1, 5, True),
                      "faithfulness": _ask("Faithfulness 0-1 > ", 0, 1, False),
                      "naturalness": _ask("Naturalness  1-5 > ", 1, 5, True),
                      "ts": time.strftime("%Y%m%d_%H%M%S")}
            responses["ratings"].append(rating)
            _save(rp, responses)

        for n, pair in enumerate(pairs, 1):
            _screen(f"Preference {n} of {len(pairs)}",
                    [("PROFILE", pair["profile_text"]),
                     ("A", pair["left"]["menu_text"]),
                     ("B", pair["right"]["menu_text"])])
            while True:
                raw = input("Which would you give this child?  a / b / = (no "
                            "preference) > ").strip().lower()
                if raw in ("q", "quit"):
                    raise Quit
                if raw in ("r", "rubric"):
                    print("\n" + _RUBRIC + "\n")
                    continue
                if raw in ("a", "b", "=", "tie", "s", ""):
                    break
                print("  Enter a, b, = , or q.")
            if raw in ("s", ""):
                continue
            responses["preferences"].append({
                "pair_id": pair["pair_id"], "annotator": args.annotator,
                "winner": {"a": "left", "b": "right"}.get(raw, "tie"),
                "ts": time.strftime("%Y%m%d_%H%M%S")})
            _save(rp, responses)

    except (Quit, KeyboardInterrupt):
        _save(rp, responses)
        print(f"\n\nSaved to {rp}.  "
              f"{len(responses['ratings'])} ratings, "
              f"{len(responses['preferences'])} preferences so far.")
        print("Re-run the same command to continue where you left off.")
        return 0

    _save(rp, responses)
    print(f"\nComplete. {len(responses['ratings'])} ratings, "
          f"{len(responses['preferences'])} preferences in {rp}.")
    return 0


def _fmt(block: Dict[str, Any]) -> str:
    if block.get("value") is None:
        return "--        (n=%d, not estimable)" % block.get("n", 0)
    ci = ("[%.2f, %.2f]" % (block["lo"], block["hi"])
          if block.get("lo") is not None else "[no interval]")
    return "%6.3f  %-14s n=%d" % (block["value"], ci, block["n"])


def cmd_report(args: argparse.Namespace) -> int:
    ip = _resolve_instrument(args.instrument)
    if ip is None:
        return 1
    kp = FEEDBACK_DIR / ip.name.replace("instrument_", "keymap_")
    if not kp.exists():
        print(f"Found {ip.name} but not its keymap ({kp.name}).")
        print("The keymap is what says which arm each item came from; without it the")
        print("ratings cannot be joined to anything. Rebuild to regenerate both:")
        print("  python benchmark/annotate.py --build "
              "--from benchmark/results/<run>_reward.json")
        return 1

    instrument, keymap = _load(ip), _load(kp)
    by_annotator: Dict[str, List[Dict[str, Any]]] = {}
    all_prefs: List[Dict[str, Any]] = []
    for rp in sorted(FEEDBACK_DIR.glob("responses_*.json")):
        r = _load(rp)
        if r["metadata"].get("instrument") != ip.name:
            continue
        by_annotator[r["metadata"]["annotator"]] = r["ratings"]
        all_prefs.extend(r["preferences"])

    if not by_annotator:
        print(f"No ratings recorded against {ip.name} yet, so there is nothing to")
        print("measure. The instrument is built and ready -- the next step is the")
        print("sitting itself:")
        print()
        print("  python benchmark/annotate.py --annotate --annotator <your-name>")
        print()
        m = instrument["metadata"]
        print(f"That is {m['n_items']} rating screens and {m['n_pairs']} preference")
        print("pairs, roughly 2-3 hours. It saves after every answer, so you can stop")
        print("and re-run the same command to continue.")
        stray = sorted(FEEDBACK_DIR.glob("responses_*.json"))
        if stray:
            print()
            print("Note: these response files exist but were recorded against a")
            print("different instrument, so they are not pooled in:")
            for sp in stray:
                other = (_load(sp).get("metadata") or {}).get("instrument")
                print(f"  {sp.name}  ->  {other}")
        return 1

    src = instrument["metadata"].get("source_run")
    run_path = next((p for p in (ROOT / "benchmark" / "results").glob("*_reward.json")
                     if src and p.name.startswith(str(src).replace(".json", ""))), None)
    reward = _load(run_path) if run_path else None
    eval_path = (ROOT / "benchmark" / "results" /
                 str(src).replace(".json", "_eval.json")) if src else None
    ev = _load(eval_path) if eval_path and eval_path.exists() else None

    ratings = [r for rows in by_annotator.values() for r in rows]

    print(f"\n{RULE}\nHuman validation - {ip.name}")
    print(f"annotators: {', '.join(sorted(by_annotator))}   "
          f"ratings: {len(ratings)}   preferences: {len(all_prefs)}\n{RULE}")

    print("\nREWARD vs HUMAN  (pairwise accuracy: of pairs a person could separate,")
    print("                  how often the higher-reward menu won)")
    pa = pairwise_accuracy(keymap["pairs"], all_prefs)
    if pa["accuracy"] is None:
        print("  no separable pairs recorded yet")
    else:
        ci = pa["ci"]
        print("  overall            %6.3f  [%s, %s]  n=%d   "
              "(human ties %d, reward ties %d)"
              % (pa["accuracy"],
                 "%.2f" % ci["lo"] if ci.get("lo") is not None else "--",
                 "%.2f" % ci["hi"] if ci.get("hi") is not None else "--",
                 pa["n_scored"], pa["human_ties"], pa["reward_ties"]))
        for stratum, blk in pa["by_stratum"].items():
            c = blk["ci"]
            print("    %-16s %6.3f  [%s, %s]  n=%d"
                  % (stratum, blk["accuracy"],
                     "%.2f" % c["lo"] if c.get("lo") is not None else "--",
                     "%.2f" % c["hi"] if c.get("hi") is not None else "--", blk["n"]))
        print("\n  `reranked` is the one that matters most: those pairs ARE the")
        print("  decisions best-of-N made, so this is the only external check on it.")

    if reward:
        weights = list((reward.get("metadata") or {}).get("weights") or {})
        rvh = reward_vs_human(ratings, keymap["items"], reward.get("records") or [], weights)
        print("\nREWARD vs HUMAN  (Spearman rho against the mean rated scale)")
        print("  overall            %s" % _fmt(rvh["overall"]))
        for comp, blk in rvh["by_component"].items():
            print("    %-16s %s" % (comp, _fmt(blk)))
        print("\n  correctness, citation_accuracy and retrieval_accuracy are corpus")
        print("  facts - a weak rho there means the task was misread, not that the")
        print("  component is wrong. relevance is where this genuinely bites.")

    if ev:
        jvh = judge_vs_human(ratings, keymap["items"],
                             (ev.get("llm_metrics") or {}).get("_judge_records") or [])
        print("\nJUDGE vs HUMAN   (discharges plan.md 4.3)")
        for scale, blk in jvh.items():
            print("  %-18s %s   %s" % (scale, _fmt(blk), blk["measure"]))

    rel = rater_reliability(by_annotator, keymap["items"])
    print("\nRATER RELIABILITY")
    for name, blk in rel["intra"].items():
        print("  intra %-12s %s" % (name, _fmt(blk)))
    for pairname, blk in rel["inter"].items():
        print("  inter %-12s %s" % (pairname, _fmt(blk)))
    if len(by_annotator) < 2:
        print("\n  Only one annotator. Inter-rater agreement is unmeasured, so the")
        print("  'human standard' above is one person's judgement - state that.")

    print("\n" + RULE)
    print("These figures measure the instruments. They change no reward: confirm with")
    print("  python benchmark/score_rewards.py --verify-only <run>_reward.json")
    return 0


def main(argv: Optional[list] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--build", action="store_true", help="build a blinded instrument")
    ap.add_argument("--from", dest="source", metavar="RUN_REWARD.JSON",
                    help="the reward file to sample from")
    ap.add_argument("--n-items", type=int, default=40, help="distinct menus to rate")
    ap.add_argument("--n-pairs", type=int, default=60, help="preference pairs")
    ap.add_argument("--repeat-fraction", type=float, default=0.2,
                    help="share of items shown twice, for intra-rater agreement")
    ap.add_argument("--overlap", type=int, default=20,
                    help="leading items a second annotator rates, for inter-rater "
                         "agreement. Decide before building: a second rater who "
                         "picks their own subset is not overlapping on purpose.")
    ap.add_argument("--seed", type=int, default=20260822,
                    help="Fixes the whole sample: which menus are rated, which "
                         "are repeated, which pairs are drawn, and which side "
                         "of each pair the higher-reward menu lands on. Same "
                         "seed and same inputs rebuild an identical instrument, "
                         "so a reader can reproduce the sample the ratings were "
                         "collected against. Change it only to draw a genuinely "
                         "new sample -- rebuilding with a different seed "
                         "invalidates ratings already collected, because they "
                         "refer to item ids that no longer mean the same menu.")

    ap.add_argument("--annotate", action="store_true", help="run a rating session")
    ap.add_argument("--annotator", default=None, help="who is rating")
    ap.add_argument("--overlap-only", action="store_true",
                    help="rate only the overlap prefix (for a second annotator)")
    ap.add_argument("--instrument", default=None,
                    help="instrument file; defaults to the newest in feedback/")

    ap.add_argument("--report", action="store_true", help="compute agreement")
    args = ap.parse_args(argv)

    if args.build:
        if not args.source:
            ap.error("--build needs --from <run>_reward.json")
        return cmd_build(args)
    if args.annotate:
        if not args.annotator:
            ap.error("--annotate needs --annotator NAME")
        return cmd_annotate(args)
    if args.report:
        return cmd_report(args)
    ap.print_help()
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
