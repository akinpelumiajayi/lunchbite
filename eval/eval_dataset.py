"""
eval_dataset.py

A small, hand-labeled evaluation set for retrieval quality testing.

Each EvalQuery has:
  - a query string (mirrors what retrieval.build_query_string() would produce
    from a real ChildProfile, or a standalone topical query for the
    guideline/allergen-rule retrieval tests)
  - a `relevant_ids` ground-truth set: which chunks SHOULD be retrieved for
    this query, judged by manually reading the actual recipe/guideline data
    (not generated by an LLM, and not guessed) -- this is what lets us
    compute precision/recall/MRR/NDCG honestly rather than vibes-checking
    retrieval output.

IMPORTANT ON GROUND-TRUTH VALIDITY: with only 9 recipes, "relevant" is
judged by a strict, auditable rule per query type:
  - allergen-exclusion queries: relevant = recipes whose `allergens_present`
    does NOT include the named allergen (i.e. the recipes that SHOULD show
    up as safe candidates)
  - topical/likes queries: relevant = recipes whose name, category, or
    ingredients genuinely match the topic (e.g. "fish" -> the 3
    fish-containing recipes), checked against document_loader output, not
    inferred
  - guideline/allergen-rule queries: relevant = the specific chunk id(s)
    that directly answer the query, identified by reading
    nutrition_guidelines.json / allergen_rules.json directly

This is a small benchmark (appropriate for a 38-chunk knowledge base) and is
intended to be illustrative and honest about its own limitations, not a
large-scale IR benchmark.
"""

from dataclasses import dataclass, field


@dataclass
class EvalQuery:
    query: str
    relevant_ids: set[str]
    source_types: list[str] | None = None   # restrict search the same way retrieval.py would
    notes: str = ""


